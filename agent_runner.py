#!/usr/bin/env python3
"""Antigravity Network Ops Agent Runner.

Demonstrates end-to-end intent translation into Ansible automation code
and triggers the human-in-the-loop GitOps workflow.
"""

import argparse
import sys
from google.antigravity.network_handler import NetworkOpsTool, network_ops_skill


SAMPLE_INTENT_PLAYBOOK = """---
- name: Configure Edge Switch Access Ports
  hosts: cisco_switches
  gather_facts: false
  tasks:
    - name: Configure access VLAN on GigabitEthernet0/1-4
      cisco.ios.ios_l2_interfaces:
        config:
          - name: GigabitEthernet0/1
            mode: access
            access:
              vlan: 10
          - name: GigabitEthernet0/2
            mode: access
            access:
              vlan: 20
        state: merged
"""


def run_pipeline(intent: str, filename: str, branch_name: str, pr_title: str):
    """Executes the NetOps automation lifecycle."""
    print(f"=== Antigravity NetOps Agent ===")
    print(f"Loaded Skill: {network_ops_skill.name}")
    print(f"Intent Received: {intent}\n")

    tool = NetworkOpsTool()

    print("[Step 1/2] Generating playbook within allowlisted paths...")
    # In full generative mode, this payload is synthesized by the LLM adhering to skill prompt rules
    write_result = tool.create_automation_code(
        filename=filename,
        content=SAMPLE_INTENT_PLAYBOOK,
    )
    print(f"-> {write_result}")

    print("\n[Step 2/2] Staging Git branch and initiating Pull Request...")
    commit_msg = f"feat(netops): {intent}\n\nAutomated change generated by Antigravity NetOps agent."
    pr_result = tool.push_and_open_pr(
        branch_name=branch_name,
        commit_message=commit_msg,
        pr_title=pr_title,
    )
    print(f"-> {pr_result}")
    print("\nWorkflow completed. Human Gate (CI dry-run + peer review) initiated.")


def main():
    parser = argparse.ArgumentParser(description="Antigravity NetOps Agent Runner")
    parser.add_argument(
        "--intent",
        type=str,
        default="Provision access VLAN 10 and 20 on edge switch ports",
        help="Natural language network change intent",
    )
    parser.add_argument(
        "--filename",
        type=str,
        default="deploy_access_ports.yml",
        help="Target playbook filename in ansible/playbooks/",
    )
    parser.add_argument(
        "--branch",
        type=str,
        default="netops/access-vlan-update",
        help="Git feature branch name",
    )
    parser.add_argument(
        "--pr-title",
        type=str,
        default="NetOps: Provision Access VLAN 10 & 20",
        help="Pull Request title",
    )

    args = parser.parse_args()
    run_pipeline(
        intent=args.intent,
        filename=args.filename,
        branch_name=args.branch,
        pr_title=args.pr_title,
    )


if __name__ == "__main__":
    main()
