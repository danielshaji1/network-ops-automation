"""Network Operations Tool Handler for Antigravity Agent.

Executes agent tool calls, writing Ansible payloads securely to the local
repository and interfacing with Git and GitHub to initiate human-in-the-loop review.
"""

import os
from typing import Optional

try:
    import git
except ImportError:
    git = None

try:
    from github import Github
except ImportError:
    Github = None

from google.antigravity import AntigravitySkill


class NetworkOpsTool:
    """Network operations context engine and GitOps coordinator."""

    def __init__(
        self,
        repo_path: str = "./",
        github_repo_name: Optional[str] = None,
    ):
        self.repo_path = os.path.abspath(repo_path)
        token = os.getenv("GITHUB_TOKEN") or os.getenv("GH_TOKEN")
        if not token:
            try:
                import subprocess
                res = subprocess.run(
                    ["gh", "auth", "token"], capture_output=True, text=True, check=False
                )
                if res.returncode == 0 and res.stdout.strip():
                    token = res.stdout.strip()
            except Exception:
                pass
        self.github_token = token
        self.github_repo_name = github_repo_name or os.getenv(
            "GITHUB_REPOSITORY", "your-org/network-infrastructure"
        )
        self.gh_client = Github(self.github_token) if (Github and self.github_token) else None

    def create_automation_code(self, filename: str, content: str) -> str:
        """Writes the AI-generated Ansible payload securely to the local git path.
        
        Args:
            filename: Name of the playbook file (e.g. 'deploy_vlans.yml').
            content: Complete YAML playbook string generated by the AI agent.

        Returns:
            Status message with the written file path.
        """
        # Ensure target file stays within allowed playbooks directory
        clean_filename = os.path.basename(filename)
        target_path = os.path.join(self.repo_path, "ansible", "playbooks", clean_filename)
        os.makedirs(os.path.dirname(target_path), exist_ok=True)

        with open(target_path, "w", encoding="utf-8") as f:
            f.write(content)
        return f"Successfully generated playbook draft at {target_path}"

    def push_and_open_pr(
        self,
        branch_name: str,
        commit_message: str,
        pr_title: str,
        base_branch: str = "main",
    ) -> str:
        """Automates the GitOps stage, handing execution off to GitHub's human gate.
        
        Args:
            branch_name: Unique feature branch name (e.g. 'netops/vlan-provisioning-101').
            commit_message: Descriptive commit message summarizing the intent and delta.
            pr_title: Pull request title for the human reviewer.
            base_branch: Target branch to merge into (defaults to 'main').

        Returns:
            Status message or PR URL.
        """
        if git is not None:
            repo = git.Repo(self.repo_path)
            if branch_name in repo.heads:
                new_branch = repo.heads[branch_name]
                new_branch.checkout()
            else:
                new_branch = repo.create_head(branch_name)
                new_branch.checkout()

            repo.git.add(A=True)
            repo.index.commit(commit_message)

            has_remote = "origin" in [remote.name for remote in repo.remotes]
            if has_remote:
                origin = repo.remote(name="origin")
                origin.push(branch_name)
            else:
                print("Notice: No remote 'origin' configured. Skipping git push upstream.")
        else:
            # Fallback to local git CLI via subprocess
            import subprocess
            subprocess.run(["git", "checkout", "-B", branch_name], cwd=self.repo_path, check=True)
            subprocess.run(["git", "add", "-A"], cwd=self.repo_path, check=True)
            subprocess.run(["git", "commit", "-m", commit_message], cwd=self.repo_path, check=True)
            remotes = subprocess.run(
                ["git", "remote"], cwd=self.repo_path, capture_output=True, text=True
            ).stdout.split()
            has_remote = "origin" in remotes
            if has_remote:
                subprocess.run(["git", "push", "origin", branch_name], cwd=self.repo_path, check=True)
            else:
                print("Notice: No remote 'origin' configured. Skipping git push upstream.")

        # Programmatically open a Pull Request for human review
        if self.gh_client and has_remote:
            try:
                gh_repo = self.gh_client.get_repo(self.github_repo_name)
                pr = gh_repo.create_pull(
                    title=pr_title,
                    body="AI generated network configuration changes.\n\n"
                    "**Human Gate Notice**: Please review the attached Ansible playbooks and CI check-mode dry-run logs before merging.",
                    head=branch_name,
                    base=base_branch,
                )
                return f"Pull Request successfully opened: {pr.html_url}"
            except Exception as e:
                return f"Changes committed to branch '{branch_name}', but failed to open PR: {e}"

        return f"Changes staged and committed to branch '{branch_name}'. Manual PR or remote push required."


# Register skill instance with tool bindings
network_ops_skill = AntigravitySkill(
    name="network_ops_automation",
    description="Generates network change code and proposes GitHub pull requests for human review.",
    system_prompt=(
        "You are an expert Network NetOps agent. Your goal is to translate plain-text intent into structured Ansible YAML code.\n"
        "CRITICAL RULES:\n"
        "1. Never directly connect to or run commands on physical infrastructure.\n"
        "2. Always generate idempotent Ansible tasks using standard collections (e.g., cisco.ios, arista.eos).\n"
        "3. Ensure all sensitive information like passwords or community strings utilize variable place holders."
    ),
    allowlist_paths=[
        "./ansible/playbooks/*",
        "./ansible/group_vars/*",
    ],
)

_handler_instance = NetworkOpsTool()
network_ops_skill.register_tool("generate_ansible_playbook", _handler_instance.create_automation_code)
network_ops_skill.register_tool("stage_git_pull_request", _handler_instance.push_and_open_pr)
